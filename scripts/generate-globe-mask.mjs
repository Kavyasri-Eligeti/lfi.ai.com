#!/usr/bin/env node
/* ==========================================================================
   Builds src/data/landMask.js - the land/sea raster behind the hero globe
   and the "Global reach" map.

   One bit per 1-degree cell, 360 x 180, row 0 at 90N, column 0 at 180W,
   packed eight cells to a byte and base64-encoded. That is ~11KB of source
   (and far less gzipped) for a coastline that reads correctly at every size
   either visual is drawn at - a 1-degree cell is smaller than one glyph.

   Antarctica is dropped (south of 60S), as it is on the corporate deck's map:
   it is a third of the visible landmass on a tilted globe and carries none of
   the story.

   Source: Natural Earth 1:110m land via the world-atlas package.
   Run with:  node scripts/generate-globe-mask.mjs
   ========================================================================== */

import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import { geoContains } from "d3-geo";

const require = createRequire(import.meta.url);
const topo = require("world-atlas/land-110m.json");
const land = feature(topo, topo.objects.land);

const W = 360;
const H = 180;
const bytes = new Uint8Array((W * H) / 8);
let count = 0;

for (let row = 0; row < H; row++) {
  const lat = 90 - row - 0.5;
  for (let col = 0; col < W; col++) {
    const lon = -180 + col + 0.5;
    if (lat < -60) continue;
    if (geoContains(land, [lon, lat])) {
      const i = row * W + col;
      bytes[i >> 3] |= 1 << (i & 7);
      count++;
    }
  }
}

const out = `/* Generated by scripts/generate-globe-mask.mjs - do not edit by hand. */
/* Natural Earth 1:110m land, 1-degree cells, ${count} land cells. */
export const MASK_W = ${W};
export const MASK_H = ${H};
export const MASK_B64 =
  "${Buffer.from(bytes).toString("base64")}";
`;

const target = path.resolve("src/data/landMask.js");
fs.writeFileSync(target, out);
console.log(`wrote ${target} (${count} land cells, ${out.length} bytes)`);
